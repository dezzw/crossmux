#!/usr/bin/env python3
"""Generate LanguageRegistry data for a selected set of hyphenation languages."""

from __future__ import annotations

import argparse
import configparser
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
GENERATED_DIR = REPO_ROOT / "lib/Epub/Epub/hyphenation/generated"
INCLUDES_PATH = GENERATED_DIR / "LanguageRegistry.includes.generated.h"
BODY_PATH = GENERATED_DIR / "LanguageRegistry.body.generated.inc"
CONFIG_PATH = GENERATED_DIR / "LanguageRegistryConfig.generated.h"

# Metadata for each supported hypher language tag (ISO 639-1 primary subtag).
LANGUAGE_SPECS: dict[str, dict[str, object]] = {
    "en": {
        "cli_name": "english",
        "is_letter": "isLatinLetter",
        "to_lower": "toLowerLatin",
        "min_prefix": 3,
        "min_suffix": 3,
    },
    "fr": {"cli_name": "french", "is_letter": "isLatinLetter", "to_lower": "toLowerLatin"},
    "de": {"cli_name": "german", "is_letter": "isLatinLetter", "to_lower": "toLowerLatin"},
    "ru": {"cli_name": "russian", "is_letter": "isCyrillicLetter", "to_lower": "toLowerCyrillic"},
    "es": {"cli_name": "spanish", "is_letter": "isLatinLetter", "to_lower": "toLowerLatin"},
    "it": {"cli_name": "italian", "is_letter": "isLatinLetter", "to_lower": "toLowerLatin"},
    "pl": {"cli_name": "polish", "is_letter": "isLatinLetter", "to_lower": "toLowerLatin"},
    "sv": {"cli_name": "swedish", "is_letter": "isLatinLetter", "to_lower": "toLowerLatin"},
    "uk": {"cli_name": "ukrainian", "is_letter": "isCyrillicLetter", "to_lower": "toLowerCyrillic"},
    "fi": {"cli_name": "finnish", "is_letter": "isLatinLetter", "to_lower": "toLowerLatin"},
}


def _parse_lang_list(raw: str) -> list[str]:
    langs = [part.strip().lower() for part in raw.split(",") if part.strip()]
    if not langs:
        raise ValueError("hyphenation language list must not be empty")
    unknown = [lang for lang in langs if lang not in LANGUAGE_SPECS]
    if unknown:
        raise ValueError(f"unknown hyphenation language tag(s): {', '.join(unknown)}")
    # Preserve order while dropping duplicates.
    seen: set[str] = set()
    ordered: list[str] = []
    for lang in langs:
        if lang not in seen:
            seen.add(lang)
            ordered.append(lang)
    return ordered


def read_langs_from_platformio(ini_path: pathlib.Path) -> str | None:
    if not ini_path.is_file():
        return None
    parser = configparser.ConfigParser()
    parser.read(ini_path)
    if parser.has_option("crosspoint", "hyphenation_langs"):
        return parser.get("crosspoint", "hyphenation_langs")
    return None


def _hyphenator_ctor(lang: str, spec: dict[str, object]) -> str:
    symbol = lang.replace("-", "_")
    min_prefix = spec.get("min_prefix")
    min_suffix = spec.get("min_suffix")
    args = f"{symbol}_patterns, {spec['is_letter']}, {spec['to_lower']}"
    if min_prefix is not None and min_suffix is not None:
        args += f", {min_prefix}, {min_suffix}"
    return f"LanguageHyphenator {spec['cli_name']}Hyphenator({args});"


def write_outputs(langs: list[str]) -> None:
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)

    # Includes live alongside the trie headers under hyphenation/generated/.
    includes = "\n".join(f'#include "hyph-{lang}.trie.h"' for lang in langs)
    hyphenators = "\n".join(_hyphenator_ctor(lang, LANGUAGE_SPECS[lang]) for lang in langs)
    entries = ",\n".join(
        f'{{"{LANGUAGE_SPECS[lang]["cli_name"]}", "{lang}", &{LANGUAGE_SPECS[lang]["cli_name"]}Hyphenator}}'
        for lang in langs
    )
    count = len(langs)

    INCLUDES_PATH.write_text(
        "// Auto-generated by generate_language_registry.py. Do not edit manually.\n#pragma once\n"
        + includes
        + "\n"
    )

    body = f"""// Auto-generated by generate_language_registry.py. Do not edit manually.
{hyphenators}

using EntryArray = std::array<LanguageEntry, {count}>;

const EntryArray& entries() {{
  static const EntryArray kEntries = {{{{
{entries}
  }}}};
  return kEntries;
}}
"""
    BODY_PATH.write_text(body)

    macro_lines = [
        "// Auto-generated by generate_language_registry.py. Do not edit manually.",
        "#pragma once",
        "",
        f'// Enabled tags (from platformio.ini [crosspoint] hyphenation_langs): {",".join(langs)}',
    ]
    for tag in LANGUAGE_SPECS:
        if tag in langs:
            macro_lines.append(f"#define CROSSMUX_HYPHENATION_LANG_{tag.upper()} 1")
        else:
            macro_lines.append(f"// CROSSMUX_HYPHENATION_LANG_{tag.upper()} not enabled")
    macro_lines.extend(
        [
            "",
            "inline constexpr const char* kCrossmuxCompiledHyphenationLangTags[] = {"
            + ", ".join(f'"{lang}"' for lang in langs)
            + "};",
            f"inline constexpr unsigned kCrossmuxCompiledHyphenationLangCount = {count};",
            "",
        ]
    )
    CONFIG_PATH.write_text("\n".join(macro_lines))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--langs",
        help="Comma-separated ISO 639-1 tags to embed (default: platformio.ini crosspoint.hyphenation_langs or en)",
    )
    parser.add_argument(
        "--platformio-ini",
        type=pathlib.Path,
        default=REPO_ROOT / "platformio.ini",
        help="Path to platformio.ini when --langs is omitted",
    )
    args = parser.parse_args()

    raw_langs = args.langs
    if raw_langs is None:
        raw_langs = read_langs_from_platformio(args.platformio_ini)
    if raw_langs is None:
        raw_langs = "en"

    langs = _parse_lang_list(raw_langs)
    write_outputs(langs)
    print(
        f"wrote LanguageRegistry includes/body ({len(langs)} language(s): {', '.join(langs)})"
    )
    print(f"wrote {CONFIG_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
