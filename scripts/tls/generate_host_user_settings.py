#!/usr/bin/env python3
"""Generate wolfssl_device_user_settings.h from Arduino-wolfSSL snapshot + CrossMux flags."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent
SNAPSHOT = ROOT / 'snapshots/arduino_wolfssl_5.7.2_user_settings.h'
OUT = ROOT / 'wolfssl_device_user_settings.h'

# Mirrors platformio.ini [base] wolfSSL-related build_flags (host tests target ESP32-S3).
CROSSMUX_PIO_WOLFSSL_FLAGS = """
#define CONFIG_IDF_TARGET_ESP32S3 1
#define WOLFSSL_TLS13
#define WOLFSSL_CLIENT_EXAMPLE
#define WOLFSSL_HAVE_SP_ECC
#define WOLFSSL_HAVE_SP_RSA
#define WOLFSSL_SP_SMALL
#define WOLFSSL_SP_4096
#define HAVE_MAX_FRAGMENT
#define HAVE_FFDHE_2048
#define HAVE_CURVE25519
#define HAVE_SNI
"""


def trim_arduino_snapshot(text: str) -> str:
    """Drop USE_CERT_BUFFERS_* (pulls certs_test.h into asm builds) and the cert macro tail."""
    lines: list[str] = []
    skip_tail = False
    for line in text.splitlines():
        if skip_tail:
            continue
        if line.strip() == '#define USE_CERT_BUFFERS_2048':
            continue
        if line.startswith('/* optional SM4 Ciphers'):
            skip_tail = True
            continue
        lines.append(line)
    return '\n'.join(lines).rstrip()


def main() -> None:
    if not SNAPSHOT.is_file():
        raise SystemExit(f'Missing snapshot: {SNAPSHOT}')
    snapshot = trim_arduino_snapshot(SNAPSHOT.read_text())
    body = f"""/* Generated by scripts/tls/generate_host_user_settings.py — do not edit. */
#ifndef CROSSMUX_WOLFSSL_DEVICE_USER_SETTINGS_H
#define CROSSMUX_WOLFSSL_DEVICE_USER_SETTINGS_H

{CROSSMUX_PIO_WOLFSSL_FLAGS.strip()}

/* Arduino-wolfSSL @ 5.7.2 user_settings.h (trimmed upstream snapshot). */
{snapshot}

#include "wolfssl_crossmux_overrides.h"

#endif
"""
    OUT.write_text(body)
    print(f'Wrote {OUT} ({OUT.stat().st_size} bytes)')


if __name__ == '__main__':
    main()
